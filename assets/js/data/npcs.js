// ============================================================
// data/npcs.js — ПЕРСОНАЖІ, З ЯКИМИ МОЖНА ПОГОВОРИТИ
//
// Кожен NPC: name, portrait (assets/images/npc/<portrait>.webp — якщо картинки
// немає, показується лише текст), nodes — вузли розмови.
// Вузол: { text, replies: [{ text, to, action, show }] }
//   text   — рядок або функція (save, ctx) → рядок
//   to     — до якого вузла перейти (за замовчуванням "start")
//   action — дія з game.js (NPC_ACTIONS): "pray", "grace", "reset"
//   show   — функція (save, ctx) → чи показувати репліку
// ctx — { member } (кого з групи стосується розмова, напр. у Розпорядника)
//
// Підключається ПІСЛЯ character.js і party.js.
// ============================================================

(function (RPG) {
  const fmt = n => Number(n).toLocaleString("uk-UA");
  const bye = { text: "Розмову закінчено.", replies: [{ text: "Заговорити знову", to: "start" }] };

  // Шинкар радить, лише коли герой уже чогось досяг
  const ostapTalks = save => {
    const ch = save.character;
    return ch.level >= 10 || RPG.getClass(ch.classId).tier > 1;
  };

  const NPCS = {
    // ---------- Шинок біля млина ----------
    ostap: {
      name: "Шинкар Остап",
      portrait: "npc_ostap",
      nodes: {
        start: {
          text: "Остап протирає кухоль і киває вам. «Заходь, мандрівнику! Сідай ближче до вогню. Чого бажаєш?»",
          replies: [
            { text: "Що чути в окрузі?", to: "rumors" },
            { text: "Кажуть, Гільдія дає людям нове ремесло. Ким я можу стати?", to: "prof", show: ostapTalks },
            { text: "Нічого, просто зайшов погрітися.", to: "bye" }
          ]
        },
        rumors: {
          text: "«Вовки на Лісовій стежці зовсім знахабніли, а в печері, кажуть, слайми плодяться, як гриби після дощу. " +
                "Ще й Король у них завівся — бачили, як золотом виблискує. Ти туди без зілля не потикайся.»",
          replies: [{ text: "Дякую за пораду.", to: "start" }]
        },
        prof: {
          text: "Остап усміхається у вуса. «Бачив я на своєму віку чимало таких, як ти. Гільдія дивиться, куди ти сам вкладав сили — " +
                "бо те, що дають роки, в усіх однакове. Головне — що в тебе найсильніше і що йде слідом. Про кого розповісти?»",
          replies: [
            { text: "Про тих, хто тримає меч і сокиру", to: "p_str" },
            { text: "Про спритних", to: "p_agi" },
            { text: "Про магів", to: "p_int" },
            { text: "Про служителів світла", to: "p_spi" },
            { text: "А як у мене всього потроху?", to: "p_even" },
            { text: "Дякую, Остапе.", to: "start" }
          ]
        },
        p_str: {
          text: "«Як найбільше в тебе Сили, а слідом Витривалість — стоятимеш лицарем у важкій броні. Сила, а за нею Спритність — " +
                "то шалений берсерк із сокирою. А як Сила, та за нею Інтелект чи Дух — прямий шлях у воїни. " +
                "Лицарем, до речі, стане й той, у кого Витривалість попереду, а Сила за нею.»",
          replies: [{ text: "А про інших?", to: "prof" }, { text: "Зрозумів, дякую.", to: "start" }]
        },
        p_agi: {
          text: "«Спритність понад усе, а за нею Інтелект чи Дух — то розбійник, тінь із кинджалом. " +
                "Спритність, а за нею Сила чи Витривалість — мисливець, що влучає здалеку.»",
          replies: [{ text: "А про інших?", to: "prof" }, { text: "Зрозумів, дякую.", to: "start" }]
        },
        p_int: {
          text: "«Маги — то ті, в кого Інтелект попереду. А далі дивись, що йде за ним: Сила — вогонь, Спритність — вітер, " +
                "Витривалість — земля, Дух — вода. Чотири школи, чотири дороги.»",
          replies: [{ text: "А про інших?", to: "prof" }, { text: "Зрозумів, дякую.", to: "start" }]
        },
        p_spi: {
          text: "«Витривалість, а слідом Дух — паладин, меч, сповнений світла. Дух понад усе, а за ним Інтелект чи Витривалість — жрець. " +
                "Дух, а за ним Сила чи Спритність — монах із посохом. А як Витривалість попереду, а за нею Спритність чи Інтелект — підеш у воїни.»",
          replies: [{ text: "А про інших?", to: "prof" }, { text: "Зрозумів, дякую.", to: "start" }]
        },
        p_even: {
          text: "«Тоді Гільдія не розбере, до чого в тебе душа лежить, і зробить воїном. Найсильніше має помітно вирізнятися — " +
                "хоча б на три очки над третім за ним. А як два рівні — рахують так: Сила, Спритність, Інтелект, Витривалість, Дух.»",
          replies: [{ text: "А про інших?", to: "prof" }, { text: "Зрозумів, дякую.", to: "start" }]
        },
        bye
      }
    },

    // ---------- Храм ----------
    nun: {
      name: "Сестра Ївга",
      portrait: "npc_nun",
      nodes: {
        start: {
          text: "Черниця в сірому вбранні запалює свічки біля вівтаря. «Мир тобі, мандрівнику. Я — сестра Ївга. Чим можу допомогти?»",
          replies: [
            { text: "Мої побратими полягли. Помолися за них.", action: "pray" },
            { text: "Благослови нас «Молитвою благодаті».", to: "grace" },
            { text: "Що це за місце?", to: "about" },
            { text: "Бувай, сестро.", to: "bye" }
          ]
        },
        grace: {
          text: save => {
            const n = RPG.partySize ? RPG.partySize(save) : 1;
            const cost = RPG.graceCost(n);
            const left = RPG.graceLeft(save);
            return "«Молитва благодаті береже тих, хто в дорозі: кожні 5 секунд повертає 2% здоров'я, а кожні 10 секунд — 3% мани. " +
              `Діє десять хвилин. Пожертва на Храм — ${fmt(cost)} золота${n > 1 ? ` за всю групу (${n} героїв)` : ""}.»` +
              (left ? ` Благодать ще з вами — близько ${Math.ceil(left / 60000)} хв. Нова молитва почне відлік заново.` : "");
          },
          replies: [
            { text: save => `Ось пожертва (${fmt(RPG.graceCost(RPG.partySize ? RPG.partySize(save) : 1))} зол.)`, action: "grace" },
            { text: "Іншим разом.", to: "start" }
          ]
        },
        about: {
          text: `«Сюди повертаються загиблі. Відроджені мають лише десяту частку сил і зовсім без мани — відновіться зіллям ` +
                "або відпочиньте в Домівці. Якщо хтось із твоєї групи поліг, а інші вижили, приходьте сюди — я помолюся за полеглих.»",
          replies: [{ text: "Дякую, сестро.", to: "start" }]
        },
        bye
      }
    },

    // ---------- Мерія (Центральний район) ----------
    steward: {
      name: "Розпорядник Захар Вергун",
      portrait: "npc_steward",
      nodes: {
        start: {
          text: "За широким столом, заваленим сувоями, сидить сивий чоловік у зеленому каптані. «Захар Вергун, розпорядник Мерії. Слухаю вас.»",
          replies: [
            { text: "Хочу почати навчання заново — перерозподілити свої вміння.", to: "reset" },
            { text: "Чим займається Мерія?", to: "about" },
            { text: "До побачення.", to: "bye" }
          ]
        },
        reset: {
          text: (save, ctx) => {
            const ms = RPG.memberSave(save, ctx.member || 0);
            const { sum } = RPG.investedAttrs(ms);
            const who = ctx.member ? `${ms.character.name}` : "ви";
            if (!sum) return `«Переписувати нічого — ${who} ще не вклали жодного очка.»`;
            return `«Можна. Мерія перепише записи: усі очки, які ${who} вкладали самі (${sum}), повернуться, і їх можна буде розподілити знову. ` +
              `Те, що дали роки, лишиться. Мито — ${fmt(RPG.attrResetPrice(ms))} золота.»`;
          },
          replies: [
            { text: (save, ctx) => `Згоден, ось ${fmt(RPG.attrResetPrice(RPG.memberSave(save, ctx.member || 0)))} золота`, action: "reset",
              show: (save, ctx) => RPG.investedAttrs(RPG.memberSave(save, ctx.member || 0)).sum > 0 },
            { text: "Я ще подумаю.", to: "start" }
          ]
        },
        about: {
          text: "«Мерія веде записи про всіх мешканців і гостей міста. Біля входу — Дошка оголошень: там авантюристи шукають собі товаришів. " +
                "А як хтось хоче змінити свій шлях — приходить до мене.»",
          replies: [{ text: "Зрозуміло.", to: "start" }]
        },
        bye
      }
    }
  };

  const STEWARD_MIN_LEVEL = 11;

  Object.assign(RPG, { NPCS, STEWARD_MIN_LEVEL });
})(window.RPG);
